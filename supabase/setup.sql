-- EDGY Game Hub: initial auth, profiles, match history, avatar storage
-- Execute once in Supabase Dashboard → SQL Editor. Review before running.
-- Anonymous players are signed in (authenticated role) but are NOT permanent accounts.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Jogador' check (char_length(display_name) between 1 and 22),
  avatar_path text,
  xp integer not null default 0 check (xp >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.match_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  client_id uuid not null,
  game text not null check (game in ('Jogo do Galo','Memória','Quiz','Reflexos')),
  result text not null check (char_length(result) between 1 and 100),
  xp integer not null check (xp between 0 and 100),
  played_at timestamptz not null default now(),
  unique (user_id, client_id)
);
create index if not exists match_history_user_recent_idx on public.match_history (user_id,played_at desc);

-- The user receives a profile automatically at the moment Auth creates the user.
create or replace function public.edgy_new_profile()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id,display_name)
  values (
    new.id,
    coalesce(nullif(left(trim(new.raw_user_meta_data->>'display_name'),22),''),'Jogador')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists edgy_auth_user_insert on auth.users;
create trigger edgy_auth_user_insert after insert on auth.users
for each row execute function public.edgy_new_profile();

-- XP is calculated from recorded games, not writable through the profiles API.
create or replace function public.edgy_match_xp()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  update public.profiles
  set xp = xp + new.xp, updated_at = now()
  where id = new.user_id;
  return new;
end;
$$;

drop trigger if exists edgy_history_insert on public.match_history;
create trigger edgy_history_insert after insert on public.match_history
for each row execute function public.edgy_match_xp();

-- RLS: authenticated users (anonymous accounts included) can only see their own data.
alter table public.profiles enable row level security;
alter table public.match_history enable row level security;

drop policy if exists "edgy_profile_select_own" on public.profiles;
create policy "edgy_profile_select_own" on public.profiles
for select to authenticated using ((select auth.uid()) = id);

drop policy if exists "edgy_profile_update_own" on public.profiles;
create policy "edgy_profile_update_own" on public.profiles
for update to authenticated
using ((select auth.uid()) = id)
with check ((select auth.uid()) = id);

drop policy if exists "edgy_history_select_own" on public.match_history;
create policy "edgy_history_select_own" on public.match_history
for select to authenticated using ((select auth.uid()) = user_id);

drop policy if exists "edgy_history_insert_own" on public.match_history;
create policy "edgy_history_insert_own" on public.match_history
for insert to authenticated with check ((select auth.uid()) = user_id);

revoke all on public.profiles from anon, authenticated;
revoke all on public.match_history from anon, authenticated;
grant select on public.profiles to authenticated;
grant update (display_name, avatar_path) on public.profiles to authenticated;
grant select, insert (user_id, client_id, game, result, xp) on public.match_history to authenticated;
grant usage, select on sequence public.match_history_id_seq to authenticated;

-- Public avatars bucket (photos are publicly viewable; uploading is restricted).
insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('edgy-avatars','edgy-avatars',true,2097152,array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set
  public=excluded.public,
  file_size_limit=excluded.file_size_limit,
  allowed_mime_types=excluded.allowed_mime_types;

drop policy if exists "edgy_avatar_insert_own_permanent" on storage.objects;
create policy "edgy_avatar_insert_own_permanent" on storage.objects
for insert to authenticated
with check (
  bucket_id='edgy-avatars'
  and (storage.foldername(name))[1] = (select auth.uid())::text
  and coalesce((select (auth.jwt()->>'is_anonymous')::boolean),true) = false
);

drop policy if exists "edgy_avatar_delete_own_permanent" on storage.objects;
create policy "edgy_avatar_delete_own_permanent" on storage.objects
for delete to authenticated
using (
  bucket_id='edgy-avatars'
  and (storage.foldername(name))[1] = (select auth.uid())::text
  and coalesce((select (auth.jwt()->>'is_anonymous')::boolean),true) = false
);

